using System.Text;
using Microsoft.CodeAnalysis;

namespace Laylua.Generators;

[Generator]
public class LuaEventFunctionDelegateWrapperGenerator : IIncrementalGenerator
{
    private const int MaxParams = 16;

    private const int LuaFunctionCallMaxTypedParams = 4;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static ctx =>
        {
            ctx.AddSource("LuaEventFunctionDelegateWrapper.g.cs", Generate());
        });
    }

    private static string Generate()
    {
        var code = new CodeWriter();
        code.Line("// <auto-generated/>");
        code.Line("#nullable enable");
        code.Line();
        code.Line("namespace Laylua.Marshaling;");
        code.Line();
        code.Line("public sealed unsafe partial class LuaEventSubscriptionTracker");
        code.OpenBrace();
        code.Line("private sealed partial class EventFunctionDelegateWrapper");
        code.OpenBrace();

        for (var i = 0; i <= MaxParams; i++)
        {
            EmitInvokeAction(code, i);
            code.Line();
        }

        for (var i = 0; i <= MaxParams; i++)
        {
            EmitInvokeFunc(code, i);
            if (i < MaxParams)
            {
                code.Line();
            }
        }

        code.CloseBrace();
        code.CloseBrace();
        return code.ToString();
    }

    private static string TypeParams(int count)
    {
        if (count == 0)
        {
            return "";
        }

        var sb = new StringBuilder();
        sb.Append('<');
        for (var i = 1; i <= count; i++)
        {
            if (i > 1)
            {
                sb.Append(", ");
            }

            sb.Append('T').Append(i);
        }

        sb.Append('>');
        return sb.ToString();
    }

    private static string Params(int count)
    {
        var sb = new StringBuilder();
        for (var i = 1; i <= count; i++)
        {
            if (i > 1)
            {
                sb.Append(", ");
            }

            sb.Append('T').Append(i).Append(" a").Append(i);
        }

        return sb.ToString();
    }

    private static string Args(int count)
    {
        var sb = new StringBuilder();
        for (var i = 1; i <= count; i++)
        {
            if (i > 1)
            {
                sb.Append(", ");
            }

            sb.Append('a').Append(i);
        }

        return sb.ToString();
    }

    private static void EmitPushArgs(CodeWriter code, int count)
    {
        for (var i = 1; i <= count; i++)
        {
            code.Line($"function.Lua.Stack.Push(a{i});");
        }
    }

    private static void EmitInvokeAction(CodeWriter code, int count)
    {
        code.Line($"internal void InvokeAction{TypeParams(count)}({Params(count)})");
        code.OpenBrace();

        if (count <= LuaFunctionCallMaxTypedParams)
        {
            code.Line($"using var _ = function.Call({Args(count)});");
        }
        else
        {
            code.Line("function.ThrowIfInvalid();");
            code.Line($"LuaFunction.PrepareForCall(function.Lua, function, {count}, out var top);");
            code.Line("try");
            code.OpenBrace();
            EmitPushArgs(code, count);
            code.Line($"using var _ = LuaFunction.PCall(function.Lua, {count}, top);");
            code.CloseBrace();
            code.Line("catch");
            code.OpenBrace();
            code.Line("lua_settop(function.Lua.State.L, top);");
            code.Line("throw;");
            code.CloseBrace();
        }

        code.CloseBrace();
    }

    private static void EmitInvokeFunc(CodeWriter code, int count)
    {
        var sb = new StringBuilder();
        sb.Append('<');
        for (var i = 1; i <= count; i++)
        {
            sb.Append('T').Append(i).Append(", ");
        }

        sb.Append("TResult>");

        code.Line($"internal TResult? InvokeFunc{sb}({Params(count)})");
        code.OpenBrace();

        if (count <= LuaFunctionCallMaxTypedParams)
        {
            code.Line($"using var results = function.Call({Args(count)});");
            code.Line("return results.Count > 0 ? results.First.GetValue<TResult>() : default;");
        }
        else
        {
            code.Line("function.ThrowIfInvalid();");
            code.Line($"LuaFunction.PrepareForCall(function.Lua, function, {count}, out var top);");
            code.Line("try");
            code.OpenBrace();
            EmitPushArgs(code, count);
            code.Line($"using var results = LuaFunction.PCall(function.Lua, {count}, top);");
            code.Line("return results.Count > 0 ? results.First.GetValue<TResult>() : default;");
            code.CloseBrace();
            code.Line("catch");
            code.OpenBrace();
            code.Line("lua_settop(function.Lua.State.L, top);");
            code.Line("throw;");
            code.CloseBrace();
        }

        code.CloseBrace();
    }
}
