using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Runtime.InteropServices;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Laylua.Generators;

[Generator]
public class LuaExportGenerator : IIncrementalGenerator
{
    private const string Namespace = "Laylua.Moon";
    private const string ExportAttribute = Namespace + ".LuaExportAttribute";
    private const string OptionalAttribute = Namespace + ".LuaOptionalAttribute";
    private const string MarshalAsAttribute = "System.Runtime.InteropServices.MarshalAsAttribute";

    private static readonly SymbolDisplayFormat TypeFormat = SymbolDisplayFormat.FullyQualifiedFormat
        .AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(EmitAttributes);

        var methods = context.SyntaxProvider
            .ForAttributeWithMetadataName(ExportAttribute,
                static (node, _) => node is MethodDeclarationSyntax method && method.Modifiers.Any(SyntaxKind.PartialKeyword),
                static (ctx, _) => TransformMethod(ctx))
            .Where(static method => method != null)
            .Select(static (method, _) => method!.Value);

        var fields = context.SyntaxProvider
            .ForAttributeWithMetadataName(ExportAttribute,
                static (node, _) => node is VariableDeclaratorSyntax,
                static (ctx, _) => TransformField(ctx))
            .Where(static field => field != null)
            .Select(static (field, _) => field!.Value);

        var combined = methods.Collect().Combine(fields.Collect());
        context.RegisterSourceOutput(combined, (ctx, data) => Emit(ctx, data.Left, data.Right));
    }

    private static void EmitAttributes(IncrementalGeneratorPostInitializationContext ctx)
    {
        ctx.AddSource("LuaExportAttribute.g.cs",
            """
            // <auto-generated />
            #nullable enable
            using System;

            namespace Laylua.Moon
            {
                [AttributeUsage(AttributeTargets.Method | AttributeTargets.Field)]
                internal class LuaExportAttribute : Attribute
                {
                    public string? ExportName { get; }
                    public bool Throws { get; set; }
                    public bool PCall { get; set; }

                    public LuaExportAttribute()
                    { }

                    public LuaExportAttribute(string exportName)
                    {
                        ExportName = exportName;
                    }
                }

                [AttributeUsage(AttributeTargets.Method | AttributeTargets.Field)]
                internal class LuaOptionalAttribute : Attribute;
            }
            """);
    }

    private static MethodExport? TransformMethod(GeneratorAttributeSyntaxContext ctx)
    {
        if (ctx.TargetSymbol is not IMethodSymbol method || method.ContainingType == null)
        {
            return null;
        }

        var exportAttr = FindAttribute(method, ExportAttribute);
        if (exportAttr == null)
        {
            return null;
        }

        var parameters = method.Parameters.Select(static param =>
        {
            IsReadOnlySpan(param.Type, out var isSpanChar, out var isSpanByte);
            return new ParamInfo
            {
                Type = param.Type.ToDisplayString(TypeFormat),
                Name = param.Name,
                RefKind = param.RefKind,
                MarshalAs = GetMarshalAsString(param),
                IsSpanChar = isSpanChar,
                IsSpanByte = isSpanByte,
                IsDelegate = param.Type.TypeKind == TypeKind.Delegate
            };
        }).ToList();

        var returnIsDelegate = method.ReturnType.TypeKind == TypeKind.Delegate;

        return new MethodExport
        {
            Namespace = GetNamespace(method.ContainingType),
            TypeName = method.ContainingType.Name,
            MethodName = method.Name,
            ExportName = GetCtorStringArg(exportAttr) ?? method.Name,
            ReturnType = method.ReturnType.ToDisplayString(TypeFormat),
            ReturnsVoid = method.ReturnsVoid,
            Parameters = parameters,
            IsOptional = HasAttribute(method, OptionalAttribute),
            Throws = GetNamedBoolArg(exportAttr, "Throws"),
            PCall = GetNamedBoolArg(exportAttr, "PCall"),
            ReturnsLuaString = IsLuaString(method.ReturnType),
            ReturnIsDelegate = returnIsDelegate,
            ReturnDelegateType = returnIsDelegate ? method.ReturnType.ToDisplayString(TypeFormat).TrimEnd('?') : null,
            Accessibility = method.DeclaredAccessibility
        };
    }

    private static FieldExport? TransformField(GeneratorAttributeSyntaxContext ctx)
    {
        if (ctx.TargetSymbol is not IFieldSymbol field || field.ContainingType == null)
        {
            return null;
        }

        var exportAttr = FindAttribute(field, ExportAttribute);
        if (exportAttr == null)
        {
            return null;
        }

        return new FieldExport
        {
            Namespace = GetNamespace(field.ContainingType),
            TypeName = field.ContainingType.Name,
            FieldName = field.Name,
            ExportName = GetCtorStringArg(exportAttr) ?? field.Name.TrimStart('_'),
            DelegateName = field.Type is INamedTypeSymbol namedType
                ? namedType.Name
                : field.Type.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat),
            IsOptional = HasAttribute(field, OptionalAttribute),
            Throws = GetNamedBoolArg(exportAttr, "Throws")
        };
    }

    private static void Emit(
        SourceProductionContext ctx,
        ImmutableArray<MethodExport> methods,
        ImmutableArray<FieldExport> fields)
    {
        if (methods.IsDefaultOrEmpty && fields.IsDefaultOrEmpty)
        {
            return;
        }

        var byType = new Dictionary<string, (string Namespace, string TypeName, List<object> Items)>();
        foreach (var method in methods)
        {
            var key = $"{method.Namespace}.{method.TypeName}";
            if (!byType.TryGetValue(key, out var entry))
            {
                byType[key] = entry = (method.Namespace, method.TypeName, new List<object>());
            }

            entry.Items.Add(method);
        }

        foreach (var field in fields)
        {
            var key = $"{field.Namespace}.{field.TypeName}";
            if (!byType.TryGetValue(key, out var entry))
            {
                byType[key] = entry = (field.Namespace, field.TypeName, new List<object>());
            }

            entry.Items.Add(field);
        }

        foreach (var kvp in byType)
        {
            var (@namespace, typeName, items) = kvp.Value;
            var writer = new CodeWriter();

            writer.Line("// <auto-generated />");
            writer.Line("#nullable enable");
            writer.Line("#pragma warning disable CS8763");
            writer.Line("using System;");
            writer.Line("using System.Runtime.CompilerServices;");
            writer.Line("using System.Runtime.InteropServices;");
            writer.Line();

            if (!string.IsNullOrEmpty(@namespace))
            {
                writer.Line($"namespace {@namespace};");
                writer.Line();
            }

            writer.Line($"unsafe partial class {typeName}");
            writer.OpenBrace();

            var exports = new List<InitEntry>();

            foreach (var method in items.OfType<MethodExport>())
            {
                EmitMethodExport(writer, method, exports);
            }

            foreach (var field in items.OfType<FieldExport>())
            {
                exports.Add(new InitEntry(field.FieldName, field.DelegateName, field.ExportName, field.IsOptional, field.Throws));
            }

            EmitInitMethod(writer, exports);

            writer.CloseBrace();
            ctx.AddSource($"{typeName}.Exports.g.cs", writer.ToString());
        }
    }

    private static void EmitMethodExport(CodeWriter code, MethodExport method, List<InitEntry> exports)
    {
        var fieldName = $"_{method.ExportName}";
        var delegateName = $"{fieldName}Delegate";

        code.Line("[UnmanagedFunctionPointer(CallingConvention.Cdecl)]");
        var delegateParams = string.Join(", ", method.Parameters.Select(FormatDelegateParam));
        code.Line($"private delegate {NativeReturnType(method)} {delegateName}({delegateParams});");
        code.Line();

        code.Line(method.IsOptional
            ? $"private static {delegateName}? {fieldName};"
            : $"private static {delegateName} {fieldName} = null!;");

        code.Line();

        var hasSpans = method.Parameters.Any(param => param.IsSpanChar || param.IsSpanByte);
        var implAttr = method.Throws || method.PCall || hasSpans ? "NoInlining" : "AggressiveInlining";
        code.Line($"[MethodImpl(MethodImplOptions.{implAttr})]");
        var methodParams = string.Join(", ", method.Parameters.Select(FormatMethodParam));
        code.Line($"{AccessibilityToString(method.Accessibility)} static partial {method.ReturnType} {method.MethodName}({methodParams})");
        code.OpenBrace();

        if (method.IsOptional)
        {
            code.Line($"if ({fieldName} == null)");
            code.OpenBrace();
            code.Line($"throw new InvalidOperationException(\"{method.MethodName} is not available.\");");
            code.CloseBrace();
            code.Line();
        }

        EmitMethodBody(code, method, fieldName);

        code.CloseBrace();
        code.Line();

        exports.Add(new InitEntry(fieldName, delegateName, method.ExportName, method.IsOptional, method.Throws));
    }

    private static void EmitMethodBody(CodeWriter writer, MethodExport method, string fieldName)
    {
        EmitDelegateConversions(writer, method);

        var charSpans = method.Parameters.Where(static param => param.IsSpanChar).ToList();
        var byteSpans = method.Parameters.Where(static param => param.IsSpanByte).ToList();
        var hasCharSpans = charSpans.Count > 0;
        var hasAnySpans = hasCharSpans || byteSpans.Count > 0;

        var pcallOpened = false;
        if (method.PCall)
        {
            var luaParam = method.Parameters.FirstOrDefault(param => param.Type.EndsWith("lua_State*"));
            writer.Line($"using (LayluaState.FromExtraSpace({luaParam.Name ?? "L"}).EnterPCallContext())");
            writer.OpenBrace();
            pcallOpened = true;
        }

        var isUsingOpened = false;
        if (hasCharSpans)
        {
            foreach (var param in charSpans)
            {
                writer.Line($"using (var _{param.Name}_bytes = ToCString({param.Name}))");
            }

            writer.OpenBrace();
            isUsingOpened = true;
        }

        var fixedOpened = false;
        if (hasAnySpans)
        {
            foreach (var param in charSpans)
            {
                writer.Line($"fixed (byte* _{param.Name}_ptr = _{param.Name}_bytes)");
            }

            foreach (var param in byteSpans)
            {
                writer.Line($"fixed (byte* _{param.Name}_ptr = {param.Name})");
            }

            writer.OpenBrace();
            fixedOpened = true;
        }

        EmitDelegateCall(writer, method, fieldName);

        if (fixedOpened)
        {
            writer.CloseBrace();
        }

        if (isUsingOpened)
        {
            writer.CloseBrace();
        }

        if (pcallOpened)
        {
            writer.CloseBrace();
        }
    }

    private static void EmitDelegateConversions(CodeWriter writer, MethodExport method)
    {
        foreach (var param in method.Parameters.Where(static param => param.IsDelegate))
        {
            writer.Line(param.Type.EndsWith("?")
                ? $"var _{param.Name}_fnptr = {param.Name} != null ? Marshal.GetFunctionPointerForDelegate({param.Name}) : (nint) 0;"
                : $"var _{param.Name}_fnptr = Marshal.GetFunctionPointerForDelegate({param.Name});");
        }
    }

    private static void EmitDelegateCall(CodeWriter writer, MethodExport method, string fieldName)
    {
        var callArgs = string.Join(", ", method.Parameters.Select(FormatCallArg));
        if (method.ReturnsLuaString)
        {
            writer.Line($"var _ptr = {fieldName}({callArgs});");
            if (method.Throws)
            {
                writer.Line("LayluaNative.ThrowIfPendingPanic();");
            }

            var lenParam = method.Parameters.FirstOrDefault(param => param.RefKind == RefKind.Out && IsNuintType(param.Type));
            writer.Line(lenParam.Name != null
                ? $"return new LuaString(_ptr, {lenParam.Name});"
                : "return new LuaString(_ptr);");
        }
        else if (method.ReturnIsDelegate)
        {
            writer.Line($"var result = {fieldName}({callArgs});");
            if (method.Throws)
            {
                writer.Line("LayluaNative.ThrowIfPendingPanic();");
            }

            writer.Line(method.ReturnType.EndsWith("?")
                ? $"return result != 0 ? Marshal.GetDelegateForFunctionPointer<{method.ReturnDelegateType}>(result) : null;"
                : $"return Marshal.GetDelegateForFunctionPointer<{method.ReturnDelegateType}>(result);");
        }
        else if (method.ReturnsVoid)
        {
            writer.Line($"{fieldName}({callArgs});");
            if (method.Throws)
            {
                writer.Line("LayluaNative.ThrowIfPendingPanic();");
            }
        }
        else
        {
            writer.Line($"var result = {fieldName}({callArgs});");
            if (method.Throws)
            {
                writer.Line("LayluaNative.ThrowIfPendingPanic();");
            }

            writer.Line("return result;");
        }
    }

    private static void EmitInitMethod(CodeWriter writer, List<InitEntry> exports)
    {
        writer.Line("internal static void InitializeExports(global::System.IntPtr libraryHandle, global::System.IntPtr throwPanicExceptionPtr)");
        writer.OpenBrace();

        foreach (var export in exports)
        {
            var ptr = $"{export.FieldName}_ptr";
            writer.Line($"if (NativeLibrary.TryGetExport(libraryHandle, \"{export.ExportName}\", out var {ptr}))");
            writer.OpenBrace();

            if (export.Throws)
            {
                writer.Line($"var asmPtr = LayluaNative.PrepareHookAsm({ptr}, throwPanicExceptionPtr);");
                writer.Line($"{export.FieldName} = Marshal.GetDelegateForFunctionPointer<{export.DelegateName}>(asmPtr);");
            }
            else
            {
                writer.Line($"{export.FieldName} = Marshal.GetDelegateForFunctionPointer<{export.DelegateName}>({ptr});");
            }

            writer.CloseBrace();

            if (!export.IsOptional)
            {
                writer.Line("else");
                writer.OpenBrace();
                writer.Line($"throw new InvalidOperationException(\"Required export '{export.ExportName}' not found.\");");
                writer.CloseBrace();
            }

            writer.Line();
        }

        writer.CloseBrace();
    }

    private static string NativeReturnType(MethodExport method)
    {
        if (method.ReturnsLuaString)
        {
            return "byte*";
        }

        if (method.ReturnIsDelegate)
        {
            return "nint";
        }

        return method.ReturnType;
    }

    private static string FormatDelegateParam(ParamInfo param)
    {
        if (param.IsSpanChar || param.IsSpanByte)
        {
            return $"byte* {param.Name}";
        }

        if (param.IsDelegate)
        {
            return $"nint {param.Name}";
        }

        var marshalAs = param.MarshalAs != null ? $"{param.MarshalAs} " : "";
        return $"{marshalAs}{RefPrefix(param.RefKind)}{param.Type} {param.Name}";
    }

    private static string FormatMethodParam(ParamInfo param)
    {
        return $"{RefPrefix(param.RefKind)}{param.Type} {param.Name}";
    }

    private static string FormatCallArg(ParamInfo param)
    {
        if (param.IsSpanChar || param.IsSpanByte)
        {
            return $"_{param.Name}_ptr";
        }

        if (param.IsDelegate)
        {
            return $"_{param.Name}_fnptr";
        }

        return $"{RefPrefix(param.RefKind)}{param.Name}";
    }

    private static string RefPrefix(RefKind kind)
    {
        return kind switch
        {
            RefKind.Ref => "ref ",
            RefKind.Out => "out ",
            RefKind.In => "in ",
            _ => ""
        };
    }

    private static bool IsNuintType(string type)
    {
        return type == "nuint" || type.EndsWith("System.UIntPtr");
    }

    private static void IsReadOnlySpan(ITypeSymbol type, out bool isChar, out bool isByte)
    {
        isChar = false;
        isByte = false;

        if (type is INamedTypeSymbol
            {
                IsGenericType: true,
                Arity: 1
            } namedType &&
            namedType.Name == "ReadOnlySpan" &&
            namedType.ContainingNamespace?.ToDisplayString() == "System")
        {
            var typeArg = namedType.TypeArguments[0];
            isChar = typeArg.SpecialType == SpecialType.System_Char;
            isByte = typeArg.SpecialType == SpecialType.System_Byte;
        }
    }

    private static bool IsLuaString(ITypeSymbol type)
    {
        return type.Name == "LuaString" && type.ContainingNamespace?.ToDisplayString() == "Laylua.Moon";
    }

    private static AttributeData? FindAttribute(ISymbol symbol, string fullName)
    {
        return symbol.GetAttributes().FirstOrDefault(attr => attr.AttributeClass?.ToDisplayString() == fullName);
    }

    private static bool HasAttribute(ISymbol symbol, string fullName)
    {
        return symbol.GetAttributes().Any(attr => attr.AttributeClass?.ToDisplayString() == fullName);
    }

    private static string? GetCtorStringArg(AttributeData attr)
    {
        return attr.ConstructorArguments.Length > 0 && attr.ConstructorArguments[0].Value is string value ? value : null;
    }

    private static bool GetNamedBoolArg(AttributeData attr, string name)
    {
        foreach (var arg in attr.NamedArguments)
        {
            if (arg.Key == name && arg.Value.Value is bool value)
            {
                return value;
            }
        }

        return false;
    }

    private static string GetNamespace(INamedTypeSymbol type)
    {
        return type.ContainingNamespace is
        {
            IsGlobalNamespace: false
        } @namespace
            ? @namespace.ToDisplayString()
            : "";
    }

    private static string? GetMarshalAsString(IParameterSymbol param)
    {
        var marshalAttr = param.GetAttributes().FirstOrDefault(static attr => attr.AttributeClass?.ToDisplayString() == MarshalAsAttribute);
        if (marshalAttr == null || marshalAttr.ConstructorArguments.Length == 0)
        {
            return null;
        }

        var unmanagedType = (UnmanagedType) (int) marshalAttr.ConstructorArguments[0].Value!;
        return $"[MarshalAs(UnmanagedType.{unmanagedType})]";
    }

    private static string AccessibilityToString(Accessibility accessibility)
    {
        return accessibility switch
        {
            Accessibility.Public => "public",
            Accessibility.Internal => "internal",
            Accessibility.Private => "private",
            Accessibility.Protected => "protected",
            Accessibility.ProtectedOrInternal => "protected internal",
            Accessibility.ProtectedAndInternal => "private protected",
            _ => "public"
        };
    }

    private struct MethodExport
    {
        public string Namespace;
        public string TypeName;
        public string MethodName;
        public string ExportName;
        public string ReturnType;
        public bool ReturnsVoid;
        public List<ParamInfo> Parameters;
        public bool IsOptional;
        public bool Throws;
        public bool PCall;
        public bool ReturnsLuaString;
        public bool ReturnIsDelegate;
        public string? ReturnDelegateType;
        public Accessibility Accessibility;
    }

    private struct FieldExport
    {
        public string Namespace;
        public string TypeName;
        public string FieldName;
        public string ExportName;
        public string DelegateName;
        public bool IsOptional;
        public bool Throws;
    }

    private struct ParamInfo
    {
        public string Type;
        public string Name;
        public RefKind RefKind;
        public string? MarshalAs;
        public bool IsSpanChar;
        public bool IsSpanByte;
        public bool IsDelegate;
    }

    private readonly struct InitEntry(string fieldName, string delegateName, string exportName, bool isOptional, bool throws)
    {
        public readonly string FieldName = fieldName;
        public readonly string DelegateName = delegateName;
        public readonly string ExportName = exportName;
        public readonly bool IsOptional = isOptional;
        public readonly bool Throws = throws;
    }
}
