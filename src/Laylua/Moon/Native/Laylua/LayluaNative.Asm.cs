// .NET 9+ detects Lua's longjmp (via RtlUnwindEx) and throws SEHException
// All the asm here exists to keep managed frames out of the longjmp path
//
// CustomLongjmpAsm - replaces longjmp in lua54's IAT, does raw restore + jmp without RtlUnwindEx (win only)
// ManagedPanicAsm - wraps every C# -> Lua callback, calls lua_error from asm after the managed
//                   wrapper returns so there's nothing managed on the stack when longjmp fires
//                   (win variant uses rcx for L, linux uses rdi)
// HookAsm - wraps Lua API calls that can error (luaL_error, lua_arith, etc.) for the non-pcall path,
//           saves all regs, sets up a recovery point, restores on panic (works on both platforms)
//
// The error flag lives in ExtraSpaceData (per-state, in Lua's extra space) so concurrent states are fine.
// LuaRaisedException is a sentinel thrown by RaiseError in pcall context to preserve the user's
// error message through the catch -> PrepareErrorInfo -> lua_error pipeline

